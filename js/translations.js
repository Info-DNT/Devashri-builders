// Get translation text by key and language
window.getTranslation = function(key, lang = window.currentLang) {
  if (!window.translations[lang]) return key;
  return window.translations[lang][key] || window.translations['en'][key] || key;
};

// Scan DOM and translate all elements with data-i18n attribute
window.translateStaticHtml = function(lang = window.currentLang) {
  // Update document title if applicable
  const titleEl = document.querySelector('title');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n');
    if (key) {
      const translation = window.getTranslation(key, lang);
      if (translation) document.title = translation;
    }
  }

  // Update elements
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = window.getTranslation(key, lang);
    if (!translation) return;

    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.placeholder !== undefined && el.getAttribute('placeholder')) {
        el.placeholder = translation;
      } else {
        el.value = translation;
      }
    } else {
      el.innerHTML = translation;
    }
  });
};
